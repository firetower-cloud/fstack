/**
 * Calling the control plane as this run's administrator.
 *
 * One command covers every read instead of twenty thin ones, which is the
 * deep-module shape this CLI is supposed to have. What it hides: the
 * ownership check before the call, the token, signing in again when the token
 * has been invalidated, and the two failures that are really instructions.
 *
 *   403 PasswordChangeRequired   the first administrator carries
 *                                must_change_password and EVERY authenticated
 *                                route answers 403 until it is cleared. A
 *                                token alone is not a usable session
 *                                (firetower#330)
 *   401                          `firetower passwd admin` invalidates every
 *                                token, so this is the ordinary consequence
 *                                of a reset. Sign in again, once
 */
import { serverUrl } from "./key.mjs";
import { readLock, updateLock, verdict, password } from "./own.mjs";
import { EXIT, fail } from "./out.mjs";

export async function signIn(plan) {
  /* Read, never derived. The password is 24 random bytes generated by `up`
     and kept only in the run lock; a command that cannot read it refuses
     rather than recomputing it, because recomputing it is the bug that
     published a live credential in a pull request comment. */
  const secret = password(plan);
  if (!secret) {
    return {
      ok: false,
      status: null,
      body: {
        code: "NoPasswordRecorded",
        detail: `no administrator password is recorded in ${plan.lock}. It is random per run and is never derived, so it cannot be recomputed`,
      },
    };
  }
  const response = await fetch(`${serverUrl(plan)}/api/v1/auth/login`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ username: "admin", password: secret }),
    signal: AbortSignal.timeout(10_000),
  });
  const body = await response.json().catch(() => null);
  if (!response.ok) {
    return { ok: false, status: response.status, body };
  }
  updateLock(plan, { token: body.token, user: body.user?.username ?? "admin" });
  return { ok: true, token: body.token, user: body.user };
}

/** A call that has already been authorised by an ownership check. */
export async function raw(plan, method, route, { body, token } = {}) {
  const url = `${serverUrl(plan)}/api/v1${route.startsWith("/") ? route : `/${route}`}`;
  const response = await fetch(url, {
    method,
    headers: {
      ...(token ? { authorization: `Bearer ${token}` } : {}),
      ...(body ? { "content-type": "application/json" } : {}),
    },
    body: body ? (typeof body === "string" ? body : JSON.stringify(body)) : undefined,
    signal: AbortSignal.timeout(30_000),
  });
  const text = await response.text();
  let parsed = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = text;
  }
  return { status: response.status, body: parsed, url, method };
}

/**
 * The checked call. Refuses before it asks.
 *
 * Returns `{ exit }` on a refusal so the caller can return it, or
 * `{ result }` on success.
 */
export async function call(plan, method, route, { body } = {}) {
  const seen = await verdict(plan);
  if (seen.verdict === "nothing-here") {
    return {
      exit: fail(EXIT.precondition, {
        problem: `nothing is answering on ${seen.at}`,
        because: seen.reasons,
        instead: [
          "control-firetower up            bring this run's own stack up",
          "control-firetower doctor        see what is and is not there",
        ],
      }),
    };
  }
  if (seen.verdict !== "mine") {
    return { exit: refuse(seen) };
  }

  const held = readLock(plan).run ?? {};
  let token = held.token;
  if (!token) {
    const signedIn = await signIn(plan);
    if (!signedIn.ok) {
      return {
        exit: fail(EXIT.precondition, {
          problem: "this run has no token and signing in did not work",
          because: [`POST /api/v1/auth/login answered ${signedIn.status}`, JSON.stringify(signedIn.body)],
          instead: [
            "control-firetower up            steps 4 to 6 make the administrator usable",
            "control-firetower doctor        says which of the six steps is missing",
          ],
        }),
      };
    }
    token = signedIn.token;
  }

  let result = await raw(plan, method, route, { body, token });

  if (result.status === 401) {
    const again = await signIn(plan);
    if (again.ok) result = await raw(plan, method, route, { body, token: again.token });
  }

  if (result.status === 403 && result.body?.code === "PasswordChangeRequired") {
    return {
      exit: fail(EXIT.precondition, {
        problem: "every authenticated route is answering 403 until the forced password change is cleared",
        because: [
          "the first administrator carries must_change_password, and a token alone is not a usable session",
          `${method} ${result.url} -> 403 PasswordChangeRequired`,
        ],
        instead: [
          "control-firetower up            step 4 runs `firetower passwd admin`, which clears the flag in the same statement",
          "control-firetower doctor        confirms it afterwards",
        ],
      }),
    };
  }

  return { result, instance: seen };
}

/** The one refusal shape for "this is not this run's instance". */
export function refuse(seen, extra = []) {
  /* `probe-failed` means nothing is holding the address — the record is what
     is stale. Suggesting `up` there was how a refusal came to name the
     command that had just refused, and an agent reading it goes round the
     same loop. The cause-specific lines above already name `down`. */
  const stale = seen.cause === "probe-failed";
  return fail(EXIT.notMine, {
    problem: `the Firetower answering on ${seen.at} is not this run's`,
    because: [
      ...seen.reasons,
      "not knowing that an instance is somebody else's is not ownership — desktop/src/servers.ts:15-44",
    ],
    instead: [
      ...extra,
      stale ? null : "Do not retry, and do not look for a free port: a run that slides to the next port",
      stale ? null : "has relocated away from the port its own evidence names.",
      stale ? null : "",
      "control-firetower doctor            what this run does own, if anything",
      stale ? null : "control-firetower up                bring up this run's own stack, on its own ports",
      `lsof -nP -iTCP:${seen.at.split(":").pop()} -sTCP:LISTEN     whose that is, if you need to know`,
    ],
    detail: {
      cause: seen.cause ?? null,
      recordedServerId: seen.recorded,
      answeringServerId: seen.answer?.serverId ?? null,
      organization: seen.answer?.organization ?? null,
      version: seen.answer?.version ?? null,
    },
  });
}
